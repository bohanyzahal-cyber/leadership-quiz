    for i, (en, he, gl, src) in enumerate(items):
        others = [x for j, x in enumerate(items) if j != i]
        ds = random.sample(others, 3)
        ref = ("מונח באנגלית; " + (src + " (המונח מופיע שם באנגלית או בעברית)" if src else "מונח מקובל לנושא שנלמד") +
               "; המרצה בשיעור החזרה 5.11.2026: במבחן יהיו מונחים באנגלית")
        e = "%s = %s: %s." % (en, he, gl)
        # A: English term -> Hebrew meaning
        opts = [he + ": " + gl] + [d[1] + ": " + d[2] for d in ds]
        c = random.randrange(4); opts.insert(c, opts.pop(0))
        out.append({"t": topic, "s": "תרגול חדש", "q": "מה פירוש המונח %s?" % en, "o": opts, "c": c, "e": e, "ref": ref})
        # B: Hebrew description -> English term (every term, distractors from the same family)
        opts = [en] + [d[0] for d in ds]
        c = random.randrange(4); opts.insert(c, opts.pop(0))
        out.append({"t": topic, "s": "תרגול חדש", "q": "איך נקרא באנגלית: %s (%s)?" % (he, gl), "o": opts, "c": c, "e": e, "ref": ref})

